let currentIndex = 0;
const slide = document.getElementById('slide');

function updateImage() {
    slide.src = images[currentIndex];
}

function nextImage() {
    currentIndex = (currentIndex + 1) % images.length;
    updateImage();
}

function prevImage() {
    currentIndex = (currentIndex - 1 + images.length) % images.length;
    updateImage();
}
updateImage();
